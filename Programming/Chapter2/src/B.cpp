#include"../lib/Interpolator_NewtonFormula.hpp"
#include"../lib/Function.hpp"
#include"../lib/LatexOutputer.hpp"
#include"../lib/Polynomial.hpp"
#include<iostream>
#include<vector>

using namespace std;

/// @cond
class F:public Function{
    using Function::Function;
    double getValue(double x) const override{
        return 1/(1+x*x);
    }
};
/// @endcond

int main(){
    F f(DefinitionDomain{-5,5});

    FunctionPointList list[4];
    int foo[4]={2,4,6,8};
    for(int i=0;i<=3;i++){
        int n=foo[i];
        list[i]=f.generatePointList(n+1,0);
    }
    
    Interpolator_N interpolator_N;
    LatexOutputer outputer("B.tex");
    outputer.quickStart("Image of Question B",DefinitionDomain{-5,5});
    outputer.addLine("{1/(1+x*x)}","exact function","dashed");
    for(int i=0;i<4;i++){
        interpolator_N.setInterpolationPoints(list[i]);
        Polynomial bar=interpolator_N.interpolate();
        cout<< "Polynomial generated by "<<foo[i]<<" interpolation points:"<<endl<<bar<<endl<<endl;
        outputer.addLine(bar.getLatexFormatString(),"$p_{n="+to_string(foo[i])+"}(x)$");
    }
    outputer.quickEnd();
    return 0;
}